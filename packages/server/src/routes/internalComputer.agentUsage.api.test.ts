import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { eq } from "drizzle-orm";
import { createApiTest } from "../test/integration/apiTest";
import { computers } from "../db/schema";
import { registerMachine } from "../services/machineService";
import { createAgent } from "../services/agentService";
import { generateComputerApiKeyMaterial } from "../services/computerCredentialService";
import { mintAgentCredential } from "../services/agentCredentialService";
import { AgentUsageReporter } from "../../../daemon/src/agentUsageReporter";
import { agentUsageRecords } from "../db/schema";
import { tokenForHuman } from "../test/integration/credentials";

const test = createApiTest({ humanActivityMuteFlagDefaultEnabled: true, onboardingOpenerFlagDefaultEnabled: false });

test("computer usage ingress authenticates the computer, validates and commits idempotently", async ({ app, db, seed }) => {
  const owner = await seed.human();
  const server = await seed.server({ owner });
  const { machine } = await registerMachine(server.id, owner.id, "usage");
  const { machine: otherMachine } = await registerMachine(server.id, owner.id, "usage-other");
  const agent = await createAgent(server.id, "UsageAgent", { runtime: "codex", model: "test", machineId: machine.id });
  const otherAgent = await createAgent(server.id, "OtherAgent", { runtime: "codex", model: "test", machineId: otherMachine.id });
  const otherServer = await seed.server({ owner });
  const foreignAgent = await createAgent(otherServer.id, "ForeignAgent", { runtime: "codex", model: "test" });
  const key = await generateComputerApiKeyMaterial();
  const [computer] = await db.insert(computers).values({ serverId: server.id, name: "usage", apiKeyHash: key.apiKeyHash, apiKeyPrefix: key.apiKeyPrefix, attachedByUserId: owner.id, machineId: machine.id }).returning();
  const agentKey = await mintAgentCredential({ agentId: agent.id, scopes: ["read"], name: "usage", createdByUserId: null });
  const record = { id: randomUUID(), serverId: server.id, computerId: computer.id, agentId: agent.id, runtime: "codex", endedAt: new Date().toISOString(), complete: true, input: 100, output: 10, cacheRead: null, cacheWrite: null, reasoning: null };
  const post = (apiKey: string, body: unknown) => fetch(`${app.baseUrl}/internal/computer/agent-usage`, { method: "POST", headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const context = await fetch(`${app.baseUrl}/internal/computer/agent-usage/context`, { headers: { Authorization: `Bearer ${key.apiKey}` } });
  assert.equal(context.status, 200);
  assert.deepEqual(await context.json(), { serverId: server.id, computerId: computer.id, machineId: machine.id });
  assert.equal((await fetch(`${app.baseUrl}/internal/computer/agent-usage/context`, { headers: { Authorization: `Bearer ${agentKey.apiKey}` } })).status, 401);
  assert.equal((await post(agentKey.apiKey, { records: [record] })).status, 401);
  assert.equal((await post(key.apiKey, { records: [{ ...record, agentId: otherAgent.id }] })).status, 403);
  assert.equal((await post(key.apiKey, { records: [{ ...record, agentId: foreignAgent.id }] })).status, 403);
  assert.equal((await post(key.apiKey, { records: [{ ...record, computerId: randomUUID() }] })).status, 403);
  const future = await post(key.apiKey, { records: [{ ...record, id: randomUUID(), endedAt: new Date(Date.now() + 10 * 60_000).toISOString() }] });
  assert.equal(future.status, 409);
  const futureBody = await future.json() as { error: string; serverTime: string };
  assert.equal(futureBody.error, "timestamp_in_future");
  assert.ok(Math.abs(Date.parse(futureBody.serverTime) - Date.now()) < 30_000);
  assert.equal((await post(key.apiKey, { records: [{ ...record, transcript: "private" }] })).status, 400);
  const ok = await post(key.apiKey, { records: [record] });
  assert.equal(ok.status, 200);
  assert.deepEqual(await ok.json(), { recordIds: [record.id], gapId: null });
  assert.equal((await post(key.apiKey, { records: [record] })).status, 200);
  assert.equal((await post(key.apiKey, { records: [{ ...record, input: 101 }] })).status, 409);
  const directory = mkdtempSync(path.join(os.tmpdir(), "usage-e2e-"));
  const reporter = new AgentUsageReporter({ serverUrl: app.baseUrl, apiKey: key.apiKey, dataDir: directory, owner: () => ({ serverId: server.id, machineId: machine.id }) });
  try {
    await reporter.tick();
    reporter.record({ agentId: agent.id, runtime: "codex", status: "ok", counts: { input: 2, output: 3, cacheRead: 4 } });
    await reporter.tick();
    const rows = await db.select().from(agentUsageRecords).where(eq(agentUsageRecords.agentId, agent.id));
    assert.equal(rows.length, 2);
    assert.ok(rows.some((row) => row.input === 2 && row.output === 3 && !row.complete));
    const from = new Date(Date.now() - 60_000).toISOString();
    const to = new Date(Date.now() + 60_000).toISOString();
    const params = new URLSearchParams({ from, to, interval: "1m" });
    const summary = await fetch(`${app.baseUrl}/api/agents/usage/summary?${params}`, { headers: { Authorization: `Bearer ${await tokenForHuman(owner.email)}`, "X-Server-Id": server.id } });
    assert.equal(summary.status, 200);
    const result = await summary.json() as { agents: Array<{ id: string; totals: { uncachedInput: number }; coverage: string }> };
    const observed = result.agents.find((entry) => entry.id === agent.id);
    assert.equal(observed?.totals.uncachedInput, 102);
    assert.equal(observed?.coverage, "partial");
  } finally { await reporter.stop(); rmSync(directory, { recursive: true, force: true }); }
  await db.update(computers).set({ revokedAt: new Date() }).where(eq(computers.id, computer.id));
  assert.equal((await post(key.apiKey, { records: [record] })).status, 401);
}, 60_000);
